create table if not exists public.guests (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  relation text not null default '',
  category text not null default 'guest'
    check (category in ('groom', 'bride', 'family', 'friend', 'colleague', 'neighbor', 'guest')),
  email text not null default '',
  phone text not null default '',
  attendance text
    check (attendance is null or attendance in ('yes', 'no', 'maybe')),
  notes text not null default '',
  invitation_type text
    check (invitation_type is null or invitation_type in ('physical', 'digital')),
  created_at timestamptz not null default now()
);

create table if not exists public.guest_wishes (
  id bigint generated by default as identity primary key,
  guest_id bigint references public.guests(id) on delete cascade,
  sender_name text not null,
  message text not null,
  created_at timestamptz not null default now()
);

alter table public.guest_wishes alter column guest_id drop not null;

alter table public.guests enable row level security;
alter table public.guest_wishes enable row level security;
